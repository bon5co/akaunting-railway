#!/bin/bash
# Railway entrypoint for Akaunting 3.1.21.
#
#   1. Populate the volume-mounted webroot from the release archive kept in the
#      `-v` image (upstream's own check: only when index.php is missing).
#   2. Make Apache listen on Railway's injected $PORT. Railway's HTTP
#      healthcheck dials the INJECTED port, not the domain's target port, so
#      the app must honour $PORT rather than pinning 80.
#   3. Install once, gated on a marker on the volume. `php artisan install` is
#      NOT idempotent: it regenerates APP_KEY and creates a second company and
#      a duplicate admin user (users has a UNIQUE(email, deleted_at), and MySQL
#      treats NULL deleted_at as distinct, so the duplicate is silent).
#   4. Run `php artisan schedule:run` in THIS container, next to Apache, so it
#      reads the same /var/www/html/.env. Console\Kernel::schedule() returns
#      early unless config('app.installed') is true, and APP_INSTALLED is
#      written into that .env by the installer -- a separate scheduler service
#      that cannot see the volume registers zero jobs and exits 0 silently.
set -euo pipefail

APP=/var/www/html

log() { echo "[railway] $*"; }

if [ ! -f "$APP/index.php" ]; then
    log "webroot empty, unpacking release archive"
    unzip -q /tmp/akaunting.zip -d "$APP"
fi

mkdir -p \
    "$APP/storage/framework/sessions" \
    "$APP/storage/framework/views" \
    "$APP/storage/framework/cache" \
    "$APP/storage/app/uploads" \
    "$APP/storage/logs" \
    "$APP/bootstrap/cache" \
    "$APP/modules"

# Static readiness file, served from both possible document roots. Railway
# rejects a healthcheckPath with a file extension, so it is also aliased to the
# extensionless /healthz that the template publishes.
printf 'ok\n' > "$APP/healthz.html"
[ -d "$APP/public" ] && printf 'ok\n' > "$APP/public/healthz.html"
cat > /etc/apache2/conf-enabled/railway-healthz.conf <<'CONF'
Alias /healthz /var/www/html/healthz.html
<Files "healthz.html">
    Require all granted
</Files>
CONF

a2dismod mpm_event mpm_worker >/dev/null 2>&1 || true
a2enmod mpm_prefork rewrite >/dev/null 2>&1 || true

LISTEN_PORT="${PORT:-8080}"
sed -ri "s/^Listen[[:space:]]+[0-9]+/Listen ${LISTEN_PORT}/" /etc/apache2/ports.conf
for vhost in /etc/apache2/sites-available/*.conf; do
    sed -ri "s#<VirtualHost \*:[0-9]+>#<VirtualHost *:${LISTEN_PORT}>#" "$vhost"
done
log "apache listening on ${LISTEN_PORT}"

if [ -z "${ADMIN_PASSWORD:-}" ]; then
    echo "[railway] ADMIN_PASSWORD is empty -- refusing to boot with an unclaimable instance" >&2
    exit 1
fi

MARKER="$APP/storage/.railway-installed"

wait_for_db() {
    local attempt=0
    until php -r '
        $h = getenv("DB_HOST"); $p = getenv("DB_PORT") ?: 3306;
        $d = getenv("DB_NAME"); $u = getenv("DB_USERNAME"); $w = getenv("DB_PASSWORD");
        try { new PDO("mysql:host=$h;port=$p;dbname=$d", $u, $w); } catch (Exception $e) { exit(1); }
    ' >/dev/null 2>&1; do
        attempt=$((attempt + 1))
        if [ "$attempt" -ge 60 ]; then
            echo "[railway] database never became reachable" >&2
            exit 1
        fi
        sleep 3
    done
}

if [ ! -f "$MARKER" ]; then
    log "first boot, waiting for database"
    wait_for_db
    log "running installer"
    php artisan install \
        --db-host="$DB_HOST" \
        --db-port="$DB_PORT" \
        --db-name="$DB_NAME" \
        --db-username="$DB_USERNAME" \
        --db-password="$DB_PASSWORD" \
        --db-prefix="$DB_PREFIX" \
        --company-name="$COMPANY_NAME" \
        --company-email="${COMPANY_EMAIL:-$ADMIN_EMAIL}" \
        --admin-email="$ADMIN_EMAIL" \
        --admin-password="$ADMIN_PASSWORD" \
        --locale="$APP_LOCALE" \
        --no-interaction
    touch "$MARKER"
    log "install complete"
else
    log "already installed, skipping installer"
fi

# APP_KEY is regenerated by the installer and written to the .env on the
# volume; keep the deploy-supplied value out of the way so it cannot diverge.
grep -q '^APP_INSTALLED' "$APP/.env" 2>/dev/null || echo "APP_INSTALLED=true" >> "$APP/.env"

chmod -R u=rwX,g=rX,o=rX "$APP"
chown -R www-data:root "$APP"

(
    while true; do
        sleep "${SCHEDULE_INTERVAL:-60}"
        su -s /bin/bash -c "cd $APP && php artisan schedule:run --no-interaction" www-data \
            >/dev/null 2>&1 || true
    done
) &
log "scheduler loop started (every ${SCHEDULE_INTERVAL:-60}s, same container, same .env)"

exec docker-php-entrypoint apache2-foreground
